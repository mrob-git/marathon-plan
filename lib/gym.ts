function eveningBlock(date: string, raceWeek: boolean): GymBlock {
  const neck = date >= NECK_BLOCK_FROM && !raceWeek
  const items: GymItem[] = [
    { id: 'ham-roll', name: 'Foam roller, hamstrings', how: 'Above the back of the knee to a hand below the sit bone. Leg turned in, then out. Pause 3 breaths on tender spots', dose: '60-90 s each' },
  ]
  if (!raceWeek) items.push({ id: 'ham-ball', name: 'Hamstring ball, pin and floss', how: 'Hard chair, 5-6/10 pressure. Hold 30 s, then 10 slow knee straighten-and-bends', dose: '2 spots each' })
  items.push({ id: 'nerve-floss', name: 'Lying rope nerve floss', how: '10 steps, 10 foot pumps, 10 wiggle-waggles. Never pulled into a stretch', dose: '1 round each' })
  if (neck) items.push({ id: 'neck-block', name: 'Neck block with the ball', how: 'Upper trap, then the corner of the shoulder blade, then under the collarbone. Light pressure', dose: '1 min each spot' })
  items.push({ id: 'bed-breathing', name: 'Resonance breathing before bed', how: '5 s in, 6 s out, through the nose', dose: '5 min' })
  return {
    title: 'Evening',
    minutes: neck ? '~15 min' : '~12 min',
    note: 'Left leg first and a bit longer. The nerve floss lives here on run days, so do not repeat it in the morning.',
    items,
  }
}


export const RUN_ROUTINE_FROM = '2026-11-28'
const NECK_BLOCK_FROM = '2026-11-30' // Calm phase of the left-side tension plan
const EASY_TYPES = new Set(['Easy', 'Strides']) // everything else counts as a session or a long run
const PHASE_LABEL: Record<string, string> = { base: 'Base', development: 'Dev', peak: 'Peak', taper: 'Taper' }

const addDays = (iso: string, n: number): string => {
  const [y, m, d] = iso.split('-').map(Number)
  return new Date(Date.UTC(y, m - 1, d + n)).toISOString().slice(0, 10)
}

let runIndex: Map<string, { run: TrainingSession; label: string }> | null = null
function plannedRun(date: string) {
  if (!runIndex) {
    runIndex = new Map()
    for (const [id, phase] of Object.entries(TRAINING_PLAN)) for (const wk of phase.weeks) for (const run of wk.sessions) {
      runIndex.set(run.date, { run, label: `${PHASE_LABEL[id] ?? phase.name} ${wk.weekNumber}` })
    }
  }
  return runIndex.get(date)
}


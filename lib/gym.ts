  'Tension, not pain: 3/10 at most, and no tingling.',
  'Ball work is for the evening. Never on the sit bone or behind the knee, and never on the morning of a session or time trial.',
  'Pain high near the sit bone, or tightness building during reps: stop the reps, jog home easy and log it.',
